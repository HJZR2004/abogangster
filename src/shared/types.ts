/**
 * Domain types shared by the main process, the preload bridge and the renderer.
 * Keep this file free of runtime dependencies (types only) so every layer can import it.
 */

// ---------------------------------------------------------------------------
// Cases (expedientes). Each case is an independent document index.
// ---------------------------------------------------------------------------

export type CaseStatus = 'activo' | 'en_espera' | 'cerrado'

export interface CaseRecord {
  id: string
  title: string
  clientName: string
  caseNumber: string
  court: string
  counterparty: string
  /** Free-text description of the case. Also sent to the AI as background context. */
  description: string
  status: CaseStatus
  /** When true, this case's content may only be processed by local AI providers. */
  localOnly: boolean
  /** Absolute path of the case folder inside the workspace. */
  folderPath: string
  createdAt: string
  updatedAt: string
}

export interface CaseSummary extends CaseRecord {
  documentCount: number
  indexedCount: number
  draftCount: number
}

export type CaseInput = Pick<
  CaseRecord,
  'title' | 'clientName' | 'caseNumber' | 'court' | 'counterparty' | 'description' | 'status' | 'localOnly'
>

// ---------------------------------------------------------------------------
// Documents and their index.
// ---------------------------------------------------------------------------

/** `case` documents belong to one case; `library` documents are shared by all cases. */
export type DocumentScope = 'case' | 'library'

export type DocumentStatus = 'pendiente' | 'indexado' | 'error' | 'no_soportado'

export interface DocumentRecord {
  id: string
  scope: DocumentScope
  caseId: string | null
  path: string
  /** Path relative to the scope root (case folder or library folder). */
  relPath: string
  fileName: string
  ext: string
  size: number
  mtimeMs: number
  status: DocumentStatus
  /** User-facing reason when status is `error` or `no_soportado`. */
  error: string | null
  charCount: number
  chunkCount: number
  embeddedChunkCount: number
  description: string
  indexedAt: string | null
  createdAt: string
}

export interface IndexingStatus {
  pending: number
  running: boolean
  currentFile: string | null
}

export interface SearchHit {
  chunkId: number
  documentId: string
  fileName: string
  relPath: string
  scope: DocumentScope
  text: string
  score: number
}

export interface SourceRef {
  documentId: string
  fileName: string
  excerpt: string
}

// ---------------------------------------------------------------------------
// Templates (machotes .docx with {{campos}}).
// ---------------------------------------------------------------------------

/** `ia`: written by the AI. `manual`: filled by the user or auto-filled from case/profile data. */
export type TemplateFieldMode = 'ia' | 'manual'

export interface TemplateField {
  /** Placeholder name as written in the .docx, e.g. `hechos` for `{{hechos}}`. */
  name: string
  label: string
  mode: TemplateFieldMode
  /** Extra guidance for the AI when writing this field. */
  instruction: string
}

export interface TemplateRecord {
  id: string
  fileName: string
  path: string
  name: string
  description: string
  /** Formatting and drafting rules that apply to every document made with this template. */
  rules: string
  fields: TemplateField[]
  /** Parse problem detected in the .docx (e.g. a broken placeholder), if any. */
  error: string | null
  updatedAt: string
}

export type TemplateUpdate = Pick<TemplateRecord, 'name' | 'description' | 'rules' | 'fields'>

// ---------------------------------------------------------------------------
// Drafts (escritos) generated by the AI and reviewed by the lawyer.
// ---------------------------------------------------------------------------

export type DraftStatus = 'borrador' | 'generando' | 'listo' | 'exportado'

export interface DraftRecord {
  id: string
  caseId: string
  /** `null` means a free-form document without a template. */
  templateId: string | null
  title: string
  instructions: string
  sourceDocumentIds: string[]
  /** Values for template placeholders (template drafts). */
  fieldValues: Record<string, string>
  /** Full text (free-form drafts). */
  body: string
  status: DraftStatus
  outputPath: string | null
  error: string | null
  createdAt: string
  updatedAt: string
}

export interface DraftListItem extends DraftRecord {
  caseTitle: string
  templateName: string | null
}

export interface DraftInput {
  caseId: string
  templateId: string | null
  title: string
  instructions: string
  sourceDocumentIds: string[]
}

export type DraftPatch = Partial<Pick<DraftRecord, 'title' | 'instructions' | 'fieldValues' | 'body'>>

export type DraftProgressEvent =
  | { draftId: string; type: 'field-start'; field: string }
  | { draftId: string; type: 'delta'; field: string; delta: string }
  | { draftId: string; type: 'field-end'; field: string; value: string }
  | { draftId: string; type: 'done' }
  | { draftId: string; type: 'error'; message: string }

/** Pseudo field name used for the body of free-form drafts in progress events. */
export const BODY_FIELD = '__cuerpo__'

// ---------------------------------------------------------------------------
// Case chat ("Preguntar sobre el caso").
// ---------------------------------------------------------------------------

export interface ChatMessage {
  id: string
  caseId: string
  role: 'user' | 'assistant'
  content: string
  sources: SourceRef[]
  createdAt: string
}

export interface ChatDeltaEvent {
  caseId: string
  delta: string
}

// ---------------------------------------------------------------------------
// Settings.
// ---------------------------------------------------------------------------

export type ChatProvider = 'ollama' | 'anthropic' | 'openai' | 'compatible'
export type EmbeddingProvider = 'ninguno' | 'ollama' | 'openai' | 'compatible'

export interface LawyerProfile {
  nombre: string
  cedula: string
  despacho: string
  domicilio: string
  telefono: string
  correo: string
  ciudad: string
  /** Jurisdiction the AI should assume, e.g. "México, Jalisco". */
  jurisdiccion: string
}

/** Settings as seen by the renderer. API keys are never exposed, only whether they exist. */
export interface PublicSettings {
  workspaceDir: string
  chat: { provider: ChatProvider; model: string }
  embedding: { provider: EmbeddingProvider; model: string }
  ollama: { baseUrl: string }
  anthropic: { hasApiKey: boolean }
  openai: { hasApiKey: boolean }
  compatible: { baseUrl: string; hasApiKey: boolean }
  /** Maximum characters of context sent to the model. 0 = automatic per provider. */
  contextChars: number
  /** When true, every case behaves as `localOnly`. */
  localOnlyGlobal: boolean
  profile: LawyerProfile
  /** Drafting rules applied to every document regardless of template. */
  generalRules: string
  /** Base font size of the interface in pixels (accessibility). */
  fontSize: number
  secretsEncrypted: boolean
}

export interface SettingsUpdate {
  chat?: { provider: ChatProvider; model: string }
  embedding?: { provider: EmbeddingProvider; model: string }
  ollama?: { baseUrl: string }
  compatible?: { baseUrl: string }
  /** `null` deletes the stored key; `undefined` leaves it untouched. */
  anthropicApiKey?: string | null
  openaiApiKey?: string | null
  compatibleApiKey?: string | null
  contextChars?: number
  localOnlyGlobal?: boolean
  profile?: LawyerProfile
  generalRules?: string
  fontSize?: number
}

export interface ConnectionTestResult {
  ok: boolean
  message: string
}

export interface AppInfo {
  version: string
  workspaceDir: string
  logsDir: string
  aiConfigured: boolean
}
